var clock = document.getElementById("clock")
var hexp = document.getElementById("hexp")
var icon = document.getElementById("icon")

function time_calculation(){
    var date = new Date()
    var sec = date.getSeconds()
    var min = date.getMinutes()
    var h = date.getHours()
    if (sec.toString().length == 1) {sec = "0"+sec}
    if (min.toString().length == 1) {min = "0"+min}
    if (h.toString().length == 1) {h = "0"+h}
    var RGB = "#" + h + min + sec
    return {sec, min, h, RGB}
}


function clockbg(){

var {sec, min, h, RGB} = time_calculation()
document.body.style.backgroundColor = RGB;
document.documentElement.style.backgroundColor = RGB;
clock.textContent = h + ":" + min + ":" + sec
}


function hexptext(){

    var {RGB} = time_calculation()
    hexp.textContent=RGB
}


